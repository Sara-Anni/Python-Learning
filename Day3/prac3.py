# Positive, Negative, or Zero Easy

# Ask the user to enter three numbers and classify each number as positive, negative, or zero using conditional statements.
# Challenge: Print the classification for all three numbers, not just one.

num1= float(input("Enter first number: "))
num2= float(input("Enter second number: "))
num3= float(input("Enter third number: "))

if num1> 0:
    print("The first number is positive")
elif num1< 0:
    print("The first number is negative")
else:
    print("The first number is zero")

if num2> 0:
    print("The second number is positive")
elif num2< 0:
    print("The second number is negative")
else:
    print("The second number is zero")

if num3> 0:
    print("The third number is positive")
elif num3< 0:
    print("The third number is negative")
else:
    print("The third number is zero")


