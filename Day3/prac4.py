    # Shopping List Updater Easy–Medium

    # Start with this list:
    # ["rice", "eggs", "milk", "bread"]
    # 1. Add "sugar" to the end.
    # 2. Insert "butter" at index 2.
    # 3. Remove "eggs".
    # 4. Print the final list and its length.
shopping_list = ["rice", "eggs", "milk", "bread"]
shopping_list.append("sugar")
shopping_list.insert(2, "butter")
shopping_list.remove("eggs")
print("Final shopping list:", shopping_list)
print("Length of the shopping list:", len(shopping_list))